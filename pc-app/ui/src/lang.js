// 번역 함수
function t(key) {
  const mode = (typeof getAppMode === 'function' ? getAppMode() : 'KR');
  const lang = mode === 'US' ? 'EN' : 'KR';
  return LANG[lang][key] || LANG['KR'][key] || key;
}

// 전체 페이지 텍스트 교체 함수
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr'); // placeholder 등 속성용
    if (attr) {
      el.setAttribute(attr, t(key));
    } else {
      el.textContent = t(key);
    }
  });
}

export { LANG, t, applyTranslations };
